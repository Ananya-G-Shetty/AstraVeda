// Helper to look up country by name or code
export function getCountryMeta(countryNameOrCode) {
  if (!countryNameOrCode) return { code: 'GLOBAL', name: 'Earth Station', flag: '🌍' };
  const found = COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === countryNameOrCode.toLowerCase() ||
      c.name.toLowerCase() === countryNameOrCode.toLowerCase()
  );
  return found || { code: 'GLOBAL', name: countryNameOrCode, flag: '🌐' };
}

